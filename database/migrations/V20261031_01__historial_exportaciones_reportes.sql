IF OBJECT_ID(N'dbo.EXPORTACIONES_REPORTES', N'U') IS NULL
BEGIN
 CREATE TABLE dbo.EXPORTACIONES_REPORTES (
  id BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT PK_EXPORTACIONES_REPORTES PRIMARY KEY,
  fecha_hora DATETIME2(7) NOT NULL,
  usuario_id INT NOT NULL,
  persona NVARCHAR(250) NOT NULL,
  tipo NVARCHAR(40) NOT NULL,
  formato VARCHAR(3) NOT NULL CONSTRAINT CK_EXPORTACIONES_FORMATO CHECK(formato IN ('pdf','csv')),
  filtros NVARCHAR(600) NOT NULL,
  cantidad_filas INT NOT NULL CONSTRAINT CK_EXPORTACIONES_FILAS CHECK(cantidad_filas >= 0)
 );
 CREATE INDEX IX_EXPORTACIONES_FECHA ON dbo.EXPORTACIONES_REPORTES(fecha_hora DESC,id DESC);
END;

